import AppKit
import ClipboardCore
import CryptoKit

/// Polls the general pasteboard (macOS has no change notification) and turns new content into history items.
@MainActor
final class PasteboardMonitor {
    private let pasteboard = NSPasteboard.general
    private let store: HistoryStore
    private var lastChangeCount: Int
    private var timer: Timer?

    // Markers defined at nspasteboard.org that password managers and other apps set.
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    init(store: HistoryStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after the app itself writes to the pasteboard so the write isn't recorded again.
    func skipCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !Preferences.isPaused else { return }

        let types = pasteboard.types ?? []
        if Preferences.ignoreConcealed && types.contains(Self.concealedType) { return }
        if Preferences.ignoreTransient && (types.contains(Self.transientType) || types.contains(Self.autoGeneratedType)) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bundleID = app?.bundleIdentifier, Preferences.ignoredApps.contains(bundleID) { return }

        guard var item = readItem(types: types) else { return }
        item.sourceBundleID = app?.bundleIdentifier
        item.sourceAppName = app?.localizedName
        store.add(item)
    }

    private func readItem(types: [NSPasteboard.PasteboardType]) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipItem(kind: .file, fileURLs: urls, contentHash: "file:" + urls.map(\.path).joined(separator: "\n"))
        }

        let string = pasteboard.string(forType: .string)
        let hasImage = types.contains(.png) || types.contains(.tiff)
        if hasImage && (string ?? "").isEmpty {
            return readImage()
        }

        if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind = ContentClassifier.classify(string)
            let rtf = kind == .text ? pasteboard.data(forType: .rtf) : nil
            let text = kind == .color || kind == .link ? string.trimmingCharacters(in: .whitespacesAndNewlines) : string
            return ClipItem(kind: kind, text: text, rtf: rtf, contentHash: "text:" + text)
        }

        if let color = NSColor(from: pasteboard), let hex = color.hexString {
            return ClipItem(kind: .color, text: hex, contentHash: "text:" + hex)
        }
        return nil
    }

    private func readImage() -> ClipItem? {
        guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        guard let fileName = store.persistence?.storeImage(png) else { return nil }
        return ClipItem(
            kind: .image, imageFile: fileName,
            imageWidth: rep.pixelsWide, imageHeight: rep.pixelsHigh,
            contentHash: "image:" + digest
        )
    }
}

extension NSColor {
    var hexString: String? {
        guard let rgb = usingColorSpace(.sRGB) else { return nil }
        let r = Int((rgb.redComponent * 255).rounded())
        let g = Int((rgb.greenComponent * 255).rounded())
        let b = Int((rgb.blueComponent * 255).rounded())
        return String(format: "#%02X%02X%02X", r, g, b)
    }

    /// Parses #RGB, #RRGGBB and #RRGGBBAA.
    convenience init?(hex: String) {
        var value = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        guard value.hasPrefix("#") else { return nil }
        value.removeFirst()
        if value.count == 3 { value = value.map { "\($0)\($0)" }.joined() }
        if value.count == 6 { value += "FF" }
        guard value.count == 8, let number = UInt64(value, radix: 16) else { return nil }
        self.init(
            srgbRed: CGFloat((number >> 24) & 0xFF) / 255,
            green: CGFloat((number >> 16) & 0xFF) / 255,
            blue: CGFloat((number >> 8) & 0xFF) / 255,
            alpha: CGFloat(number & 0xFF) / 255
        )
    }
}
